// ─── Enterprise Handler Factory ──────────────────────────────

function withRefund<P = any, R = any>(
  operation: ScopeAndEventsConfig<P, R>["operation"],
  entity: string,
  getScope: (args: P) => { companyId?: string; branchId?: string },
  handler: (ctx: any, args: P, userId: Id<"users">) => Promise<R>,
) {
  return async (ctx: any, args: P) => {
    const userId = await getAuthUserId(ctx);
    if (!userId) throw new Error("Not authenticated");
    const scope = getScope(args);
    const wrapped = withScopeAndEvents<P, R>(
      {
        operation,
        module: "finance",
        entity,
        getEntityCompanyId: () => scope.companyId,
        getEntityBranchId: () => scope.branchId,
        getUserId: () => userId as Id<"users">,
        notifyViaMatrix: true,
        triggerWorkflow: true,
        triggerAutomation: true,
        registerSearch: true,
        signalDashboard: true,
        autoGenerateDocs: [
          {
            documentType: "refund_voucher",
            contextBuilder: (a: any, r: any) => ({
              refundId: r?.toString() || "",
              studentId: a.studentId,
              amount: a.amount,
            }),
          },
        ],
      },
      (ctx2, args2) => handler(ctx2, args2, userId as Id<"users">),
    );
    return wrapped(ctx, args);
  };
}

// ─── CREATE REFUND REQUEST ───────────────────────────────

export const createRefundRequest = mutation({
  args: {
    token: v.optional(v.string()),
    studentId: v.optional(v.id("studentMaster")),
    transactionId: v.optional(v.id("paymentTransactions")),
    invoiceId: v.optional(v.id("feeInvoices")),
    amount: v.number(),
    reason: v.string(),
    reasonCategory: v.union(v.literal("academic"), v.literal("administrative"), v.literal("financial"), v.literal("withdrawal"), v.literal("other")),
    notes: v.optional(v.string()),
    companyId: v.optional(v.id("companies")),
    branchId: v.optional(v.id("branches")),
  },
  handler: withRefund("create", "refund_request", (a) => ({
    companyId: a.companyId,
    branchId: a.branchId,
  }), async (ctx, args, userId) => {
    const { companyId, branchId, ...rest } = args;
    return ctx.db.insert("refundRequests", {
      ...rest,
      status: "draft",
      createdBy: userId,
      createdAt: Date.now(),
      updatedAt: Date.now(),
    });
  }),
});

// ─── SUBMIT FOR APPROVAL ─────────────────────────────────

export const submitRefundForApproval = mutation({
  args: {
    token: v.optional(v.string()),
    id: v.id("refundRequests"),
    companyId: v.optional(v.id("companies")),
    branchId: v.optional(v.id("branches")),
  },
  handler: withRefund("update", "refund_submit", (a) => ({
    companyId: a.companyId,
    branchId: a.branchId,
  }), async (ctx, args) => {
    const request = await ctx.db.get(args.id);
    if (!request) throw new Error("Refund request not found");
    if (request.status !== "draft") throw new Error("Only draft refunds can be submitted");
    await ctx.db.patch(args.id, { status: "pending", updatedAt: Date.now() });
    return args.id;
  }),
});

// ─── APPROVE / REJECT ────────────────────────────────────

export const approveRefund = mutation({
  args: {
    token: v.optional(v.string()),
    id: v.id("refundRequests"),
    approve: v.boolean(),
    notes: v.optional(v.string()),
    companyId: v.optional(v.id("companies")),
    branchId: v.optional(v.id("branches")),
  },
  handler: withRefund("approve", "refund_decision", (a) => ({
    companyId: a.companyId,
    branchId: a.branchId,
  }), async (ctx, args, userId) => {
    const request = await ctx.db.get(args.id);
    if (!request) throw new Error("Refund request not found");
    if (request.status !== "pending") throw new Error("Refund is not pending approval");

    await ctx.db.patch(args.id, {
      status: args.approve ? "approved" : "rejected",
      approvedBy: userId,
      approvedAt: Date.now(),
      notes: args.notes || request.notes,
      updatedAt: Date.now(),
    });
    return args.id;
  }),
});

