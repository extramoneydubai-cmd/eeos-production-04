export const getRefundSummary = query({
  args: { startDate: v.optional(v.number()), endDate: v.optional(v.number()) },
  handler: async (ctx, args) => {
    const userId = await getAuthUserId(ctx);
    let requests = await ctx.db.query("refundRequests").collect();
    if (userId) {
      const { ScopeEngine } = await import("./scopeEngine");
      const scope = await ScopeEngine.forUser(ctx, userId);
      requests = scope.filterByScope(requests);
    }
    if (args.startDate) requests = requests.filter((r: any) => r.createdAt >= args.startDate!);
    if (args.endDate) requests = requests.filter((r: any) => r.createdAt <= args.endDate!);

    return {
      totalCount: requests.length,
      totalRequested: requests.reduce((s: number, r: any) => s + r.amount, 0),
      totalApproved: requests.filter((r: any) => r.status === "approved" || r.status === "processing" || r.status === "completed")
        .reduce((s: number, r: any) => s + r.amount, 0),
      totalCompleted: requests.filter((r: any) => r.status === "completed").reduce((s: number, r: any) => s + r.amount, 0),
      totalRejected: requests.filter((r: any) => r.status === "rejected").reduce((s: number, r: any) => s + r.amount, 0),
      pendingCount: requests.filter((r: any) => r.status === "pending").length,
      approvedCount: requests.filter((r: any) => r.status === "approved" || r.status === "processing" || r.status === "completed").length,
      completedCount: requests.filter((r: any) => r.status === "completed").length,
    };
  },
});
