// ─── Archive Student (Enterprise-Integrated) ───────────────

export const archiveStudent = mutation({
  args: {
    token: v.optional(v.string()),
    studentId: v.id("studentMaster"),
    reason: v.optional(v.string()),
    performedBy: v.id("users"),
  },
  handler: withScopeAndEvents(
    {
      operation: "delete",
      module: "admission",
      entity: "student",
      eventType: Events.ADMISSION.STUDENT_CANCELLED,
      title: "Student Archived",
      getUserId: (args) => args.performedBy,
      getEntityCompanyId: () => undefined,
      getEntityBranchId: () => undefined,
      notifyViaMatrix: true, // Notify parent, counsellor, finance, branch head, CEO if over threshold
    },
    async (ctx, args) => {
      const student = await ctx.db.get(args.studentId);
      if (!student) throw new Error("Student not found");

      const now = Date.now();
      await ctx.db.patch(args.studentId, { currentStatus: "cancelled" as any, updatedAt: now });

      await ctx.db.insert("studentStatusHistory", {
        studentId: args.studentId,
        fromStatus: student.currentStatus,
        toStatus: "cancelled",
        remarks: args.reason || "Student archived",
        changedBy: args.performedBy,
        changedAt: now,
        createdAt: now,
      });

      return args.studentId;
    }
  ),
});

