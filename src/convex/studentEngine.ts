/**
 * Student Engine — Enterprise-integrated Student CRUD
 *
 * Every operation uses:
 *   - withScopeAndEvents() wrapper for ScopeEngine + Event Pipeline + Timeline + Audit
 *   - Notification Matrix for automatic notification routing
 *   - Auto-document generation for admission/consent forms
 *   - withScopeCheck() for query-side read access enforcement
 *
 * Business logic is pure — no manual scope checks, event publishing,
 * timeline creation, or notification sending.
 */

