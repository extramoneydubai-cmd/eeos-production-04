import { defineTable } from "convex/server";
import { v } from "convex/values";

export const financeTables = {
  financeBankAccounts: defineTable({
    name: v.string(),
    code: v.string(),
    accountNumber: v.string(),
    bankName: v.string(),
    branchName: v.optional(v.string()),
    ifscCode: v.optional(v.string()),
    swiftCode: v.optional(v.string()),
    accountType: v.string(),
    isDefault: v.boolean(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  financeCurrencies: defineTable({
    name: v.string(),
    code: v.string(),
    symbol: v.string(),
    isoCode: v.string(),
    isBase: v.boolean(),
    exchangeRate: v.optional(v.number()),
    decimalPlaces: v.number(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  financeDiscountCategories: defineTable({
    name: v.string(),
    code: v.string(),
    discountType: v.string(),
    isPercentage: v.boolean(),
    maxValue: v.optional(v.number()),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  financeExpenseCategories: defineTable({
    name: v.string(),
    code: v.string(),
    expenseType: v.string(),
    budgetable: v.boolean(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  financeFeeCategories: defineTable({
    name: v.string(),
    code: v.string(),
    feeType: v.string(),
    isRecurring: v.boolean(),
    isOptional: v.boolean(),
    isRefundable: v.boolean(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  financeFinancialYears: defineTable({
    name: v.string(),
    code: v.string(),
    startDate: v.number(),
    endDate: v.number(),
    isCurrent: v.boolean(),
    isClosed: v.boolean(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  financeGstRates: defineTable({
    name: v.string(),
    code: v.string(),
    gstType: v.string(),
    cgstRate: v.number(),
    sgstRate: v.number(),
    igstRate: v.optional(v.number()),
    totalRate: v.number(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  financeIncomeCategories: defineTable({
    name: v.string(),
    code: v.string(),
    incomeType: v.string(),
    isTaxable: v.boolean(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  financePaymentModes: defineTable({
    name: v.string(),
    code: v.string(),
    modeCategory: v.string(),
    isDigital: v.boolean(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  financeTaxTypes: defineTable({
    name: v.string(),
    code: v.string(),
    taxCategory: v.string(),
    taxRate: v.number(),
    isCompound: v.boolean(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  payment_commitments: defineTable({
    leadId: v.id("leadMaster"),
    amount: v.number(),
    commitDate: v.number(),
    reason: v.optional(v.string()),
    confidence: v.union(v.literal("low"), v.literal("medium"), v.literal("high")),
    ownerId: v.id("users"),
    status: v.union(v.literal("active"), v.literal("completed"), v.literal("expired"), v.literal("cancelled")),
    paymentId: v.optional(v.id("leadPayments")),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("ownerId", ["ownerId"])
    .index("commitDate", ["commitDate"]),
  payment_installments: defineTable({
    planId: v.id("payment_plans"),
    leadId: v.id("leadMaster"),
    installmentNumber: v.number(),
    amount: v.number(),
    dueDate: v.number(),
    status: v.union(v.literal("planned"), v.literal("due"), v.literal("paid"), v.literal("overdue"), v.literal("cancelled")),
    paymentId: v.optional(v.id("leadPayments")),
    paidAt: v.optional(v.number()),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("planId", ["planId"])
    .index("dueDate", ["dueDate"]),
  payment_pdcs: defineTable({
    leadId: v.id("leadMaster"),
    chequeNumber: v.string(),
    bank: v.string(),
    chequeDate: v.number(),
    amount: v.number(),
    attachment: v.optional(v.string()),
    depositDate: v.optional(v.number()),
    status: v.union(v.literal("scheduled"), v.literal("deposited"), v.literal("cleared"), v.literal("bounced"), v.literal("cancelled")),
    linkedPaymentId: v.optional(v.id("leadPayments")),
    createdBy: v.id("users"),
    depositedBy: v.optional(v.id("users")),
    bouncedAt: v.optional(v.number()),
    bounceReason: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("depositDate", ["depositDate"]),
  payment_plans: defineTable({
    leadId: v.id("leadMaster"),
    totalAmount: v.number(),
    installmentCount: v.number(),
    installmentAmount: v.number(),
    frequency: v.union(v.literal("weekly"), v.literal("monthly"), v.literal("quarterly"), v.literal("custom")),
    startDate: v.number(),
    graceDays: v.number(),
    status: v.union(v.literal("active"), v.literal("completed"), v.literal("cancelled")),
    createdBy: v.id("users"),
    createdAt: v.number(),
    updatedAt: v.number(),
  }),
};