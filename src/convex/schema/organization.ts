import { defineTable } from "convex/server";
import { v } from "convex/values";

export const organizationTables = {
  boards: defineTable({
    name: v.string(),
    code: v.string(),
    subVerticalId: v.optional(v.id("subVerticals")),
    verticalId: v.optional(v.id("verticals")),
    description: v.optional(v.string()),
    status: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("subVerticalId", ["subVerticalId"]),
  branchMetrics: defineTable({
    branchId: v.id("branches"),
    period: v.string(),
    periodStart: v.number(),
    periodEnd: v.number(),
    newLeads: v.number(),
    activeLeads: v.number(),
    demoRate: v.number(),
    trialRate: v.number(),
    admissionRate: v.number(),
    revenue: v.number(),
    pendingFollowups: v.number(),
    slaCompliance: v.number(),
    counselorCount: v.number(),
    createdAt: v.number(),
  })
    .index("branchId", ["branchId"])
    .index("period", ["period"]),
  branches: defineTable({
    name: v.string(),
    code: v.string(),
    parentType: v.optional(v.union(v.literal("group"), v.literal("company"))),
    parentId: v.optional(v.string()),
    organizationId: v.optional(v.id("organizations")),
    email: v.optional(v.string()),
    phone: v.optional(v.string()),
    address: v.optional(v.string()),
    isActive: v.optional(v.boolean()),
    description: v.optional(v.string()),
    color: v.optional(v.string()),
    icon: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("by_org", ["organizationId"]),
  departments: defineTable({
    name: v.string(),
    code: v.string(),
    parentType: v.optional(v.union(v.literal("group"), v.literal("company"))),
    parentId: v.optional(v.string()),
    branchId: v.optional(v.id("branches")),
    managerId: v.optional(v.id("users")),
    isActive: v.optional(v.boolean()),
    description: v.optional(v.string()),
    color: v.optional(v.string()),
    icon: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
  }),
  designations: defineTable({
    name: v.string(),
    code: v.string(),
    reportsTo: v.optional(v.id("designations")),
    status: v.string(),
    description: v.optional(v.string()),
    color: v.optional(v.string()),
    icon: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("code", ["code"]),
  orgBranches: defineTable({
    name: v.string(),
    code: v.string(),
    color: v.string(),
    icon: v.string(),
    city: v.string(),
    state: v.string(),
    country: v.string(),
    address: v.optional(v.string()),
    phone: v.optional(v.string()),
    email: v.optional(v.string()),
    managerName: v.optional(v.string()),
    displayOrder: v.number(),
    isActive: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("displayOrder", ["displayOrder"]),
  orgCompanies: defineTable({
    name: v.string(),
    code: v.string(),
    color: v.string(),
    icon: v.string(),
    legalName: v.optional(v.string()),
    registrationNumber: v.optional(v.string()),
    taxNumber: v.optional(v.string()),
    email: v.optional(v.string()),
    phone: v.optional(v.string()),
    website: v.optional(v.string()),
    address: v.optional(v.string()),
    city: v.string(),
    state: v.string(),
    country: v.string(),
    logoUrl: v.optional(v.string()),
    description: v.optional(v.string()),
    displayOrder: v.number(),
    isActive: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("displayOrder", ["displayOrder"]),
  orgDepartments: defineTable({
    name: v.string(),
    code: v.string(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  orgDesignations: defineTable({
    name: v.string(),
    code: v.string(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  orgTeams: defineTable({
    name: v.string(),
    code: v.string(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  organizations: defineTable({
    name: v.string(),
    code: v.string(),
    description: v.optional(v.string()),
    email: v.optional(v.string()),
    phone: v.optional(v.string()),
    address: v.optional(v.string()),
    taxId: v.optional(v.string()),
    isActive: v.optional(v.boolean()),
    color: v.optional(v.string()),
    icon: v.optional(v.string()),
    createdAt: v.optional(v.number()),
    updatedAt: v.optional(v.number()),
  }),
  subVerticals: defineTable({
    name: v.string(),
    code: v.string(),
    verticalId: v.id("verticals"),
    description: v.optional(v.string()),
    status: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("verticalId", ["verticalId"]),
  teams: defineTable({
    name: v.string(),
    code: v.string(),
    departmentId: v.id("departments"),
    description: v.optional(v.string()),
    leadId: v.optional(v.id("users")),
    leadUserId: v.optional(v.id("users")),
    isActive: v.optional(v.boolean()),
    color: v.optional(v.string()),
    icon: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("by_dept", ["departmentId"])
    .index("by_lead", ["leadId"]),
  verticals: defineTable({
    name: v.string(),
    code: v.string(),
    description: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("code", ["code"]),
};