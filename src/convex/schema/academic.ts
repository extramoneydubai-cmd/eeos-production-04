import { defineTable } from "convex/server";
import { v } from "convex/values";

export const academicTables = {
  academicBatchTypes: defineTable({
    name: v.string(),
    code: v.string(),
    deliveryMode: v.string(),
    timingCategory: v.string(),
    description: v.optional(v.string()),
    displayOrder: v.number(),
    color: v.string(),
    icon: v.string(),
    isActive: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("displayOrder", ["displayOrder"]),
  academicBatches: defineTable({
    name: v.string(),
    code: v.string(),
    programId: v.id("academicPrograms"),
    batchTypeId: v.id("academicBatchTypes"),
    academicSessionId: v.id("academicSessions"),
    capacity: v.optional(v.number()),
    minStrength: v.optional(v.number()),
    maxStrength: v.optional(v.number()),
    startDate: v.optional(v.number()),
    endDate: v.optional(v.number()),
    description: v.optional(v.string()),
    sequence: v.number(),
    color: v.string(),
    icon: v.string(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("programId", ["programId"])
    .index("batchTypeId", ["batchTypeId"]),
  academicBoards: defineTable({
    name: v.string(),
    code: v.string(),
    shortName: v.string(),
    color: v.string(),
    icon: v.string(),
    country: v.string(),
    educationLevel: v.string(),
    website: v.optional(v.string()),
    description: v.optional(v.string()),
    displayOrder: v.number(),
    isActive: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("displayOrder", ["displayOrder"]),
  academicClassrooms: defineTable({
    name: v.string(),
    code: v.string(),
    building: v.optional(v.string()),
    floor: v.optional(v.number()),
    roomNumber: v.optional(v.string()),
    capacity: v.optional(v.number()),
    hasMultimedia: v.boolean(),
    hasAirConditioning: v.boolean(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  academicLanguages: defineTable({
    name: v.string(),
    code: v.string(),
    isoCode: v.string(),
    nativeName: v.optional(v.string()),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    isRTL: v.boolean(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  academicMediums: defineTable({
    name: v.string(),
    code: v.string(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  academicPrograms: defineTable({
    subVerticalId: v.id("academicSubVerticals"),
    name: v.string(),
    code: v.string(),
    programType: v.string(),
    duration: v.number(),
    durationUnit: v.string(),
    deliveryMode: v.string(),
    description: v.optional(v.string()),
    displayOrder: v.number(),
    color: v.string(),
    icon: v.string(),
    isActive: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("subVerticalId", ["subVerticalId"]),
  academicSections: defineTable({
    name: v.string(),
    code: v.string(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  academicSemesters: defineTable({
    name: v.string(),
    code: v.string(),
    academicSessionId: v.id("academicSessions"),
    semesterNumber: v.number(),
    startDate: v.optional(v.number()),
    endDate: v.optional(v.number()),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }),
  academicSessions: defineTable({
    name: v.string(),
    code: v.string(),
    academicYear: v.string(),
    color: v.string(),
    icon: v.string(),
    startDate: v.number(),
    endDate: v.number(),
    admissionStartDate: v.optional(v.number()),
    admissionEndDate: v.optional(v.number()),
    description: v.optional(v.string()),
    sequence: v.number(),
    isCurrent: v.boolean(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  academicStreams: defineTable({
    name: v.string(),
    code: v.string(),
    educationLevel: v.string(),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("sequence", ["sequence"]),
  academicSubVerticals: defineTable({
    verticalId: v.id("academicVerticals"),
    name: v.string(),
    code: v.string(),
    color: v.string(),
    icon: v.string(),
    description: v.optional(v.string()),
    displayOrder: v.number(),
    isActive: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }),
  academicSubjects: defineTable({
    name: v.string(),
    code: v.string(),
    category: v.string(),
    subjectType: v.string(),
    description: v.optional(v.string()),
    displayOrder: v.number(),
    color: v.string(),
    icon: v.string(),
    isTheory: v.boolean(),
    isPractical: v.boolean(),
    isActive: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("category", ["category"]),
  academicTerms: defineTable({
    name: v.string(),
    code: v.string(),
    academicSessionId: v.id("academicSessions"),
    termNumber: v.number(),
    startDate: v.optional(v.number()),
    endDate: v.optional(v.number()),
    description: v.optional(v.string()),
    color: v.string(),
    icon: v.string(),
    sequence: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }),
  academicVerticals: defineTable({
    name: v.string(),
    code: v.string(),
    color: v.string(),
    icon: v.string(),
    educationCategory: v.string(),
    description: v.optional(v.string()),
    minimumAge: v.optional(v.number()),
    maximumAge: v.optional(v.number()),
    displayOrder: v.number(),
    isActive: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index("displayOrder", ["displayOrder"]),
  courses: defineTable({
    courseCode: v.string(),
    courseName: v.string(),
    verticalId: v.optional(v.id("verticals")),
    subVerticalId: v.optional(v.id("subVerticals")),
    boardId: v.optional(v.id("boards")),
    baseFee: v.number(),
    description: v.optional(v.string()),
    status: v.union(v.literal("active"), v.literal("archived"), v.literal("draft")),
    createdBy: v.id("users"),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("courseCode", ["courseCode"])
    .index("status", ["status"]),
};